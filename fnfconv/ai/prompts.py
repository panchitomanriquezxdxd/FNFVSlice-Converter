CHEATSHEET = """\
V-SLICE (Friday Night Funkin' 0.3+) HSCRIPT RULES
- Scripts are `.hxc` files. No top-level statements: everything lives inside a class.
- Gameplay logic goes in a Module:
    import funkin.modding.module.Module;
    import funkin.play.PlayState;
    class MyMod extends Module { public function new() { super('myMod', 1000); } }
  Hooks (override them): onCreate(ScriptEvent), onUpdate(UpdateScriptEvent) [event.elapsed],
  onBeatHit(SongTimeScriptEvent) [event.beat], onStepHit(SongTimeScriptEvent) [event.step],
  onSongStart(ScriptEvent), onSongEnd(ScriptEvent), onCountdownStart(CountdownScriptEvent),
  onNoteHit(NoteScriptEvent) [event.note.noteData.kind, event.cancelEvent()], onNoteMiss(NoteScriptEvent),
  onGameOver(ScriptEvent), onPause(PauseScriptEvent), onResume(ScriptEvent).
- A Module is global: ALWAYS guard it so it only runs where intended:
    if (PlayState.instance == null) return;
- Useful: PlayState.instance.camGame / camHUD, PlayState.instance.health, FlxG.camera, FlxG.sound,
  Paths.image('x'), Paths.sound('x'), FlxSprite, FlxTween, FlxEase, FlxTimer, FlxG.camera.shake/flash.
- Custom chart events are classes extending SongEvent (see the template you are given).

LUA/PSYCH -> V-SLICE MAPPING HINTS
 onCreate/onCreatePost -> onCreate | onSongStart -> onSongStart | onBeatHit/onStepHit -> same name
 onUpdate/onUpdatePost -> onUpdate(event) using event.elapsed | goodNoteHit -> onNoteHit | noteMiss -> onNoteMiss
 makeLuaSprite + addLuaSprite -> new FlxSprite(x,y).loadGraphic(Paths.image(..)); PlayState.instance.add(sprite)
 doTweenX/Y/Alpha -> FlxTween.tween(obj, {x: v}, dur, {ease: FlxEase.xxx}) | runTimer -> new FlxTimer().start(t, cb)
 cameraShake('game',i,d) -> FlxG.camera.shake(i,d) | cameraFlash('game','FFFFFF',d) -> FlxG.camera.flash(0xFFFFFFFF,d)
 playSound -> FlxG.sound.play(Paths.sound(name)) | setProperty('health',v) -> PlayState.instance.health = v
 triggerEvent(name,a,b) -> no direct equivalent: leave a TODO.

HARD RULES
1. Never invent APIs. If there is no equivalent in this cheat-sheet or standard Flixel, write
   `// TODO(convert): <what the original did>` and keep the original line as a comment.
2. Output ONLY the .hxc source. No markdown fences, no explanations.
3. Start the file with: // Auto-generated by FNFVSlice-Converter (AI). REVIEW BEFORE USE.
"""

