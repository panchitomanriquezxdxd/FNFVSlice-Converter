"""Lua/HScript -> V-Slice .hxc. Uses the LLM when available, falls back to a commented stub otherwise."""
from __future__ import annotations

import re
from pathlib import Path

from ..util import pascal, slug, write_text
from .client import AIError
from .prompts import SYSTEM_TRANSLATOR, review_prompt, translator_prompt

HEADER = "// Auto-generated by FNFVSlice-Converter ({how}). REVIEW BEFORE USE.\n"
HOOKS = {  # original callback -> (V-Slice hook signature)
    "onCreate": "onCreate(event:ScriptEvent)", "onCreatePost": "onCreate(event:ScriptEvent)",
    "onSongStart": "onSongStart(event:ScriptEvent)", "onBeatHit": "onBeatHit(event:SongTimeScriptEvent)",
    "onStepHit": "onStepHit(event:SongTimeScriptEvent)", "onUpdate": "onUpdate(event:UpdateScriptEvent)",
    "onUpdatePost": "onUpdate(event:UpdateScriptEvent)", "goodNoteHit": "onNoteHit(event:NoteScriptEvent)",
    "noteMiss": "onNoteMiss(event:NoteScriptEvent)", "onEndSong": "onSongEnd(event:ScriptEvent)",
    "onGameOver": "onGameOver(event:ScriptEvent)", "create": "onCreate(event:ScriptEvent)",
    "postCreate": "onCreate(event:ScriptEvent)", "beatHit": "onBeatHit(event:SongTimeScriptEvent)",
    "stepHit": "onStepHit(event:SongTimeScriptEvent)", "update": "onUpdate(event:UpdateScriptEvent)",
}


def strip_fences(s):
    m = re.search(r"```(?:\w+)?\n(.*?)```", s, re.S)
    return (m.group(1) if m else s).strip()


def sane(code):
    return "class " in code and code.count("{") == code.count("}") and code.count("(") == code.count(")")


def guard(kind, ctx):
    if kind == "song":
        return f"if (PlayState.instance == null || PlayState.instance.currentSong == null || PlayState.instance.currentSong.id != '{ctx['song']}') return;"
    if kind == "stage":
        return f"if (PlayState.instance == null || PlayState.instance.currentStage == null || PlayState.instance.currentStage.stageId != '{ctx['stage']}') return;"
    return "if (PlayState.instance == null) return;"


def make_stub(kind, ctx, source, reason):
    com = "\n".join("// " + l for l in source.splitlines())
    if kind == "event":
        p = "param" if ctx.get("params") == "param" else "value"
        return (HEADER.format(how="STUB - " + reason) + "import funkin.play.event.SongEvent;\nimport funkin.data.event.SongEventSchema;\n"
                "import funkin.data.event.SongEventSchema.SongEventFieldType;\nimport funkin.play.PlayState;\n\n"
                f"class {ctx['cls']} extends SongEvent\n{{\n  public function new() {{ super('{ctx['name']}'); }}\n"
                "  public override function handleEvent(data:SongEventData):Void\n  {\n    if (PlayState.instance == null) return;\n"
                "    // TODO(convert): port the original logic below\n  }\n"
                "  public override function getEventSchema():SongEventSchema\n  {\n    return new SongEventSchema([\n"
                f"      {{name: '{p}1', title: 'Value 1', defaultValue: '', type: SongEventFieldType.STRING}},\n"
                f"      {{name: '{p}2', title: 'Value 2', defaultValue: '', type: SongEventFieldType.STRING}}\n    ]);\n  }}\n"
                f"  public override function getTitle():String {{ return '{ctx.get('title', ctx['name'])}'; }}\n}}\n\n"
                "// ---- ORIGINAL SCRIPT ----\n" + com + "\n")
    funcs = list(dict.fromkeys(re.findall(r"function\s+(\w+)\s*\(", source)))
    hooks, seen = [], set()
    for f in funcs:
        sig = HOOKS.get(f)
        if sig and sig not in seen:
            seen.add(sig)
            hooks.append(f"  public override function {sig}:Void\n  {{\n    {guard(kind, ctx)}\n    // TODO(convert): port '{f}' from the original script\n  }}\n")
    return (HEADER.format(how="STUB - " + reason) + "import funkin.modding.module.Module;\nimport funkin.play.PlayState;\nimport flixel.FlxG;\n\n"
            f"class {ctx['cls']} extends Module\n{{\n  public function new() {{ super('{ctx['id']}', 1000); }}\n\n" + "\n".join(hooks) +
            "}\n\n// ---- ORIGINAL SCRIPT ----\n" + com + "\n")


def translate_all(tasks, ai, out, mod_id, report, review=False):
    used = set()
    for t in tasks:
        path, kind = Path(t["path"]), t["kind"]
        try:
            src = path.read_text(encoding="utf-8", errors="replace")
        except OSError as e:
            report.warn(f"{path.name}: unreadable ({e})")
            continue
        base = pascal(path.stem) + {"song": "Song", "stage": "Stage", "event": "Event", "notetype": "Note", "global": "Mod"}[kind]
        cls = base
        i = 2
        while cls in used:
            cls, i = f"{base}{i}", i + 1
        used.add(cls)
        ctx = {**t, "cls": cls, "id": slug(f"{mod_id}-{cls}"), "file": path.name}
        if kind == "event":
            ctx["name"] = t["name"]
        lang = "Lua (Psych Engine)" if path.suffix == ".lua" else "HScript"
        reason, code, how = "no AI configured", None, "stub"
        if ai is not None:
            if len(src) > 60000:
                reason = "script too large (>60k chars)"
            else:
                try:
                    code = strip_fences(ai.complete(SYSTEM_TRANSLATOR, translator_prompt(kind, ctx, src, lang), 8000))
                    if review and sane(code):
                        code = strip_fences(ai.complete(SYSTEM_TRANSLATOR, review_prompt(code, "none reported"), 8000))
                    if sane(code):
                        how = "AI"
                    else:
                        reason, code = "AI output failed sanity check", None
                except AIError as e:
                    reason, code = f"AI error: {e}", None
        if code is None:
            code = make_stub(kind, ctx, src, reason)
            report.warn(f"{path.name}: stub generated ({reason}). Port manually.")
            report.add_todo(f"Port {path.name} -> scripts/{mod_id}/{kind}/{cls}.hxc")
        else:
            if not code.lstrip().startswith("// Auto-generated"):
                code = HEADER.format(how="AI") + code
            report.ai(f"{path.name} -> {cls}.hxc translated by AI. Review before shipping.")
        write_text(Path(out) / "scripts" / mod_id / kind / f"{cls}.hxc", code + ("\n" if not code.endswith("\n") else ""))
        report.bump(f"scripts_{how}")
